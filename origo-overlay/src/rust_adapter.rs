use std::collections::BTreeMap;

use crate::{
    engine::{self, Event},
    error::{OverlayError, Result},
    model::{LocatedOverlay, Selector},
};

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum RustSymbolKind {
    Function,
    Parameter,
    Variable,
    Return,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RustSymbol {
    pub kind: RustSymbolKind,
    pub name: String,
    pub function: Option<String>,
    pub line: usize,
    pub column: usize,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ResolvedEvent {
    pub event: Event,
    pub line: usize,
    pub column: usize,
    pub matched_symbol: String,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RustAnalysis {
    pub symbols: Vec<RustSymbol>,
    pub resolved: Vec<ResolvedEvent>,
    pub unresolved: Vec<String>,
}

pub fn analyze(source: &str, overlays: &[LocatedOverlay]) -> RustAnalysis {
    let symbols = index_symbols(source);
    let mut resolved = Vec::new();
    let mut unresolved = Vec::new();

    for located in overlays {
        for (rule, event) in located
            .overlay
            .rules
            .iter()
            .zip(engine::plan(&located.overlay))
        {
            let matches = resolve_selector(&rule.selector, &symbols);
            if matches.is_empty() {
                unresolved.push(event.selector.clone());
            } else {
                for symbol in matches {
                    resolved.push(ResolvedEvent {
                        event: event.clone(),
                        line: symbol.line,
                        column: symbol.column,
                        matched_symbol: display_symbol(symbol),
                    });
                }
            }
        }
    }

    RustAnalysis {
        symbols,
        resolved,
        unresolved,
    }
}

pub fn validate(analysis: &RustAnalysis) -> Result<()> {
    if analysis.unresolved.is_empty() {
        Ok(())
    } else {
        Err(OverlayError::Validation(format!(
            "seletores Rust nao resolvidos: {}",
            analysis.unresolved.join(", ")
        )))
    }
}

pub fn instrument(source: &str, analysis: &RustAnalysis) -> String {
    let mut by_line: BTreeMap<usize, Vec<&ResolvedEvent>> = BTreeMap::new();
    for event in &analysis.resolved {
        by_line.entry(event.line).or_default().push(event);
    }

    let mut output = String::new();
    output.push_str("// Generated by Origo Overlay Rust Adapter 0.2.0\n");
    output.push_str("// Instrumentation is declarative: markers do not execute code.\n");

    for (index, line) in source.lines().enumerate() {
        let line_number = index + 1;
        if let Some(events) = by_line.get(&line_number) {
            let indentation: String = line.chars().take_while(|c| c.is_whitespace()).collect();
            for resolved in events {
                output.push_str(&indentation);
                output.push_str("// @origo-site overlay=\"");
                output.push_str(&escape(&resolved.event.overlay));
                output.push_str("\" action=\"");
                output.push_str(&escape(&resolved.event.action));
                output.push_str("\" selector=\"");
                output.push_str(&escape(&resolved.event.selector));
                output.push_str("\" payload=\"");
                output.push_str(&escape(&resolved.event.payload));
                output.push_str("\"\n");
            }
        }
        output.push_str(line);
        output.push('\n');
    }
    output
}

pub fn analysis_json(analysis: &RustAnalysis) -> String {
    let resolved = analysis.resolved.iter().map(|r| format!(
        "    {{\"overlay\":\"{}\",\"action\":\"{}\",\"selector\":\"{}\",\"payload\":\"{}\",\"line\":{},\"column\":{},\"symbol\":\"{}\"}}",
        escape(&r.event.overlay), escape(&r.event.action), escape(&r.event.selector),
        escape(&r.event.payload), r.line, r.column, escape(&r.matched_symbol)
    )).collect::<Vec<_>>().join(",\n");
    let unresolved = analysis
        .unresolved
        .iter()
        .map(|u| format!("\"{}\"", escape(u)))
        .collect::<Vec<_>>()
        .join(",");
    format!(
        "{{\n  \"schema\":\"origo-overlay-rust-plan/v1\",\n  \"resolved\":[\n{}\n  ],\n  \"unresolved\":[{}]\n}}\n",
        resolved, unresolved
    )
}

pub fn index_symbols(source: &str) -> Vec<RustSymbol> {
    let clean = mask_comments_and_strings(source);
    let functions = discover_functions(&clean);
    let mut symbols = Vec::new();

    for function in &functions {
        let (line, column) = byte_location(&clean, function.name_start);
        symbols.push(RustSymbol {
            kind: RustSymbolKind::Function,
            name: function.name.clone(),
            function: None,
            line,
            column,
        });
        symbols.push(RustSymbol {
            kind: RustSymbolKind::Return,
            name: function.name.clone(),
            function: Some(function.name.clone()),
            line,
            column,
        });
        for parameter in &function.parameters {
            let (line, column) = byte_location(&clean, parameter.offset);
            symbols.push(RustSymbol {
                kind: RustSymbolKind::Parameter,
                name: parameter.name.clone(),
                function: Some(function.name.clone()),
                line,
                column,
            });
        }
    }

    let mut byte_offset = 0usize;
    for (line_index, line) in clean.split_inclusive('\n').enumerate() {
        let text = line.strip_suffix('\n').unwrap_or(line);
        let trimmed = text.trim_start();
        let base_column = text.len() - trimmed.len() + 1;
        for (name, column) in parse_let_bindings(trimmed, base_column) {
            let name_position = text.find(&name).unwrap_or(0);
            let absolute = byte_offset + name_position;
            let owner = functions
                .iter()
                .find(|function| absolute >= function.body_start && absolute <= function.body_end)
                .map(|function| function.name.clone());
            symbols.push(RustSymbol {
                kind: RustSymbolKind::Variable,
                name,
                function: owner,
                line: line_index + 1,
                column,
            });
        }
        byte_offset += line.len();
    }
    symbols
}

#[derive(Debug, Clone)]
struct ParameterSpan {
    name: String,
    offset: usize,
}

#[derive(Debug, Clone)]
struct FunctionSpan {
    name: String,
    name_start: usize,
    parameters: Vec<ParameterSpan>,
    body_start: usize,
    body_end: usize,
}

fn discover_functions(source: &str) -> Vec<FunctionSpan> {
    let mut functions = Vec::new();
    let mut search = 0usize;
    while let Some(fn_start) = find_keyword_from(source, "fn", search) {
        let mut cursor = fn_start + 2;
        cursor = skip_whitespace(source, cursor);
        let name_start = cursor;
        cursor = take_identifier(source, cursor);
        if cursor == name_start {
            search = fn_start + 2;
            continue;
        }
        let name = source[name_start..cursor].to_string();
        let Some(relative_open) = source[cursor..].find('(') else {
            break;
        };
        let open = cursor + relative_open;
        let Some(close) = find_matching_delimiter(source, open, '(', ')') else {
            search = open + 1;
            continue;
        };
        let parameters = parse_parameters(source, open + 1, close);
        let Some(relative_body) = source[close + 1..].find('{') else {
            search = close + 1;
            continue;
        };
        let body_start = close + 1 + relative_body;
        let body_end = find_matching_delimiter(source, body_start, '{', '}')
            .unwrap_or(source.len().saturating_sub(1));
        functions.push(FunctionSpan {
            name,
            name_start,
            parameters,
            body_start,
            body_end,
        });
        search = body_start + 1;
    }
    functions
}

fn parse_parameters(source: &str, start: usize, end: usize) -> Vec<ParameterSpan> {
    let section = &source[start..end];
    let mut parameters = Vec::new();
    let mut local_offset = 0usize;
    for raw in split_top_level(section, ',') {
        let leading = raw.len() - raw.trim_start().len();
        let trimmed = raw.trim();
        if !trimmed.is_empty() && !is_self_parameter(trimmed) {
            let before_type = trimmed.split(':').next().unwrap_or(trimmed).trim();
            let candidate = before_type
                .split_whitespace()
                .rfind(|part| !matches!(*part, "mut" | "ref" | "pub"))
                .unwrap_or("");
            if !candidate.is_empty() && candidate.chars().next().is_some_and(is_ident_start) {
                let candidate_local = raw.find(candidate).unwrap_or(leading);
                parameters.push(ParameterSpan {
                    name: candidate.to_string(),
                    offset: start + local_offset + candidate_local,
                });
            }
        }
        local_offset += raw.len() + 1;
    }
    parameters
}

fn is_self_parameter(value: &str) -> bool {
    matches!(value.trim(), "self" | "mut self" | "&self" | "&mut self")
        || value.trim().ends_with(" self")
}

fn find_keyword_from(source: &str, keyword: &str, mut offset: usize) -> Option<usize> {
    while let Some(position) = source[offset..].find(keyword) {
        let absolute = offset + position;
        let before_ok = absolute == 0
            || !source[..absolute]
                .chars()
                .next_back()
                .is_some_and(is_ident_continue);
        let after_position = absolute + keyword.len();
        let after_ok = after_position >= source.len()
            || !source[after_position..]
                .chars()
                .next()
                .is_some_and(is_ident_continue);
        if before_ok && after_ok {
            return Some(absolute);
        }
        offset = after_position;
    }
    None
}

fn skip_whitespace(source: &str, mut offset: usize) -> usize {
    while offset < source.len() {
        let character = source[offset..].chars().next().unwrap();
        if !character.is_whitespace() {
            break;
        }
        offset += character.len_utf8();
    }
    offset
}

fn take_identifier(source: &str, mut offset: usize) -> usize {
    while offset < source.len() {
        let character = source[offset..].chars().next().unwrap();
        if !is_ident_continue(character) {
            break;
        }
        offset += character.len_utf8();
    }
    offset
}

fn find_matching_delimiter(
    source: &str,
    open: usize,
    opening: char,
    closing: char,
) -> Option<usize> {
    let mut depth = 0usize;
    for (relative, character) in source[open..].char_indices() {
        if character == opening {
            depth += 1;
        } else if character == closing {
            depth = depth.saturating_sub(1);
            if depth == 0 {
                return Some(open + relative);
            }
        }
    }
    None
}

fn byte_location(source: &str, offset: usize) -> (usize, usize) {
    let prefix = &source[..offset.min(source.len())];
    let line = prefix.bytes().filter(|byte| *byte == b'\n').count() + 1;
    let column = prefix
        .rsplit('\n')
        .next()
        .map(|tail| tail.chars().count() + 1)
        .unwrap_or(1);
    (line, column)
}

fn resolve_selector<'a>(selector: &Selector, symbols: &'a [RustSymbol]) -> Vec<&'a RustSymbol> {
    symbols
        .iter()
        .filter(|symbol| match selector {
            Selector::Variable(name) => {
                symbol.kind == RustSymbolKind::Variable && symbol.name == *name
            }
            Selector::Function(name) => {
                symbol.kind == RustSymbolKind::Function && symbol.name == *name
            }
            Selector::Return(name) => symbol.kind == RustSymbolKind::Return && symbol.name == *name,
            Selector::Parameter { function, name } => {
                symbol.kind == RustSymbolKind::Parameter
                    && symbol.function.as_deref() == Some(function.as_str())
                    && symbol.name == *name
            }
        })
        .collect()
}

fn parse_let_bindings(line: &str, base_column: usize) -> Vec<(String, usize)> {
    let mut result = Vec::new();
    let mut search = 0usize;
    while let Some(relative) = line[search..].find("let ") {
        let position = search + relative;
        if position > 0 && is_ident_continue(line[..position].chars().last().unwrap()) {
            search = position + 4;
            continue;
        }
        let after = &line[position + 4..];
        let after_trim = after.trim_start_matches("mut ").trim_start();
        if after_trim.starts_with('(') || after_trim.starts_with('[') || after_trim.starts_with('{')
        {
            search = position + 4;
            continue;
        }
        let name: String = after_trim
            .chars()
            .take_while(|c| is_ident_continue(*c))
            .collect();
        if !name.is_empty() {
            let local = line[position + 4..].find(&name).unwrap_or(0);
            result.push((name, base_column + position + 4 + local));
        }
        search = position + 4;
    }
    result
}

fn mask_comments_and_strings(source: &str) -> String {
    let chars: Vec<char> = source.chars().collect();
    let mut out = String::with_capacity(source.len());
    let mut i = 0usize;
    let mut block_depth = 0usize;
    let mut string = false;
    let mut character = false;
    let mut escaped = false;
    while i < chars.len() {
        let c = chars[i];
        let next = chars.get(i + 1).copied();
        if c == '\n' {
            out.push('\n');
            i += 1;
            continue;
        }
        if block_depth > 0 {
            if c == '/' && next == Some('*') {
                block_depth += 1;
                out.push(' ');
                out.push(' ');
                i += 2;
                continue;
            }
            if c == '*' && next == Some('/') {
                block_depth -= 1;
                out.push(' ');
                out.push(' ');
                i += 2;
                continue;
            }
            out.push(' ');
            i += 1;
            continue;
        }
        if string || character {
            if escaped {
                escaped = false;
                out.push(' ');
                i += 1;
                continue;
            }
            if c == '\\' {
                escaped = true;
                out.push(' ');
                i += 1;
                continue;
            }
            if (string && c == '"') || (character && c == '\'') {
                string = false;
                character = false;
            }
            out.push(' ');
            i += 1;
            continue;
        }
        if c == '/' && next == Some('/') {
            while i < chars.len() && chars[i] != '\n' {
                out.push(' ');
                i += 1;
            }
            continue;
        }
        if c == '/' && next == Some('*') {
            block_depth = 1;
            out.push(' ');
            out.push(' ');
            i += 2;
            continue;
        }
        if c == '"' {
            string = true;
            out.push(' ');
            i += 1;
            continue;
        }
        if c == '\'' {
            character = true;
            out.push(' ');
            i += 1;
            continue;
        }
        out.push(c);
        i += 1;
    }
    out
}

fn split_top_level(source: &str, delimiter: char) -> Vec<&str> {
    let mut output = Vec::new();
    let mut start = 0usize;
    let mut depth = 0usize;
    for (index, character) in source.char_indices() {
        match character {
            '(' | '[' | '{' | '<' => depth += 1,
            ')' | ']' | '}' | '>' => depth = depth.saturating_sub(1),
            _ => {}
        }
        if character == delimiter && depth == 0 {
            output.push(&source[start..index]);
            start = index + character.len_utf8();
        }
    }
    output.push(&source[start..]);
    output
}

fn is_ident_start(c: char) -> bool {
    c == '_' || c.is_alphabetic()
}
fn is_ident_continue(c: char) -> bool {
    is_ident_start(c) || c.is_ascii_digit()
}
fn display_symbol(symbol: &RustSymbol) -> String {
    match &symbol.function {
        Some(f) => format!("{}::{}", f, symbol.name),
        None => symbol.name.clone(),
    }
}
fn escape(s: &str) -> String {
    s.replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\n', "\\n")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{
        carrier,
        policy::{self, Policy},
    };
    use std::path::Path;

    const SOURCE: &str = r#"// @origo-begin
// overlay "x" {
// capability observe;
// capability emit;
// observe variable "temperatura" -> trace "T3";
// observe parameter "calcular::forca" -> trace "P1";
// observe return "calcular" -> emit "done";
// }
// @origo-end
fn calcular(forca: f64, temperatura: f64) -> f64 {
    let indice = forca / temperatura;
    indice
}
fn main() { let temperatura = 188.7; println!("{}", temperatura); }
"#;

    #[test]
    fn indexa_funcoes_parametros_variaveis_e_retorno() {
        let symbols = index_symbols(SOURCE);
        assert!(
            symbols
                .iter()
                .any(|s| s.kind == RustSymbolKind::Function && s.name == "calcular")
        );
        assert!(
            symbols
                .iter()
                .any(|s| s.kind == RustSymbolKind::Parameter && s.name == "forca")
        );
        assert!(
            symbols
                .iter()
                .any(|s| s.kind == RustSymbolKind::Variable && s.name == "indice")
        );
        assert!(
            symbols
                .iter()
                .any(|s| s.kind == RustSymbolKind::Return && s.name == "calcular")
        );
    }

    #[test]
    fn resolve_todos_os_seletores_do_exemplo() {
        let overlays = carrier::extract_from_host(Path::new("x.rs"), SOURCE).unwrap();
        policy::validate(&overlays[0].overlay, &Policy::default()).unwrap();
        let analysis = analyze(SOURCE, &overlays);
        validate(&analysis).unwrap();
        assert_eq!(analysis.resolved.len(), 3); // variável em main, parâmetro e retorno
    }

    #[test]
    fn instrumentacao_adiciona_marcadores_sem_alterar_codigo() {
        let overlays = carrier::extract_from_host(Path::new("x.rs"), SOURCE).unwrap();
        let analysis = analyze(SOURCE, &overlays);
        let generated = instrument(SOURCE, &analysis);
        assert!(generated.contains("@origo-site"));
        assert!(generated.contains("fn calcular(forca: f64"));
    }

    #[test]
    fn reconhece_assinatura_multilinha_com_genericos() {
        let source = r#"fn calcular<T>(
    forca: f64,
    temperatura: f64,
    transformacao: Option<Result<T, String>>,
) -> f64
where
    T: Clone,
{
    let indice = forca / temperatura;
    indice
}
"#;
        let symbols = index_symbols(source);
        let parameters: Vec<_> = symbols
            .iter()
            .filter(|symbol| symbol.kind == RustSymbolKind::Parameter)
            .map(|symbol| symbol.name.as_str())
            .collect();
        assert_eq!(parameters, vec!["forca", "temperatura", "transformacao"]);
        assert!(symbols.iter().any(|symbol| {
            symbol.kind == RustSymbolKind::Variable
                && symbol.name == "indice"
                && symbol.function.as_deref() == Some("calcular")
        }));
    }
}
